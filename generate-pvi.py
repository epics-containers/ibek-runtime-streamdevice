"""Generate a PVI device yaml for each entity model of each pattern.

StreamDevice templates carry no asyn parameters, so `pvi convert device` finds
nothing in them. This script reads each entity model's templates directly and
writes `<model>.pvi.device.yaml` next to them, then gives the model a `pvi:`
block in the pattern's `*.ibek.support.yaml` so that `ibek runtime generate2`
renders `<model>.pvi.bob` and links it from the IOC index.

No record is dropped. Each record lands in one of four places:

- the main group, named after the model;
- `Settings`: autosaved output records (with their readbacks);
- `Comms`: asyn records, the comms disable switch and comms counters;
- `Internal`: a sub-screen, opened by a button, holding the plumbing -
  calc/fanout/seq style records, raw replies parsed by other records,
  pollers, and records named as internal (RAW, CALC, FAN, ...).

The strongest signal is the DLS `# % gui` annotations that drove the DLS EDM
screens. They were stripped from the templates (see strip-dls-annotations.py)
but are read back from git history at ANNOTATION_REF: an annotated record goes
on the main screen under its annotated label and group heading. `#% controldesk`
and `#% archiver` tags still in the templates also keep a record on the main
screen.

An output record is shown together with its readback when a readback is
found by name (SETX/X, X_SP/X, X:SET/X, X:WR/X:RD, X/X_RBV, ...).

A pattern may hold `pvi-overrides.yaml` (not vendored) forcing records to a
place, keyed by entity model, each a list of regexes matched (fullmatch)
against the record name as written in the template, e.g.

    enzLoCuM4:
      main: ['\\$\\(device\\):CONF']
      internal: ['.*:RANGEMAX']

The generated files carry a header with a hash of their body. A device yaml
without that header, or whose body no longer matches its hash, was edited by
hand: it is never overwritten, only reported.

    uv run generate-pvi.py                  # every pattern
    uv run generate-pvi.py enzLoCuM4 leybold
    uv run generate-pvi.py --check          # exit 1 if anything would change
    uv run generate-pvi.py --report out.tsv # per-record classification
"""

