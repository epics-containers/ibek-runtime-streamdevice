def body_hash(body: str) -> str:
    return hashlib.sha256(body.encode()).hexdigest()


def render(device: Device, scratch: Path) -> str:
    tmp = scratch / "device.pvi.device.yaml"
    device.serialize(tmp)
    body = tmp.read_text()
    tmp.unlink()
    return f"{HEADER}{body_hash(body)}\n{body}"


def hand_edited(path: Path) -> str | None:
    """Why an existing device yaml must not be overwritten, or None."""
    if not path.exists():
        return None
    text = path.read_text()
    first, _, body = text.partition("\n")
    if not first.startswith(HEADER):
        return "no generator header"
    if first[len(HEADER) :].strip() != body_hash(body):
        return "body edited since generation"
    return None


def ui_macros(
    records: list[Record], params: dict, args: dict
) -> tuple[dict[str, str | None], dict[str, str], list[str]]:
    """(ui_macros, literal substitutions, unresolved macros) for record names."""
    macros: dict[str, str | None] = {}
    subs: dict[str, str] = {}
    unresolved: list[str] = []
    passes_all = any("*" in k or "?" in k for k in args)
    for r in records:
        for m in MACRO.finditer(r.name):
            name, default = m[1], m[2]
            if name in macros or name in subs:
                continue
            if name in args and args[name] is not None:
                macros[name] = args[name]
            elif name in params and (passes_all or name in args):
                macros[name] = None
            elif default is not None:
                subs[name] = default
            else:
                unresolved.append(name)
                macros[name] = None
    return macros, subs, unresolved


def load_overrides(pattern: Path) -> dict:
    path = pattern / OVERRIDES
    return yaml.safe_load(path.read_text()) or {} if path.exists() else {}


def models_of(support: Path) -> list[dict]:
    return yaml.safe_load(support.read_text()).get("entity_models", [])


def pvi_block(device_file: str, macros: dict[str, str | None]) -> list[str]:
    lines = ["    pvi:", f"      yaml_path: {device_file}"]
    if macros:
        lines.append("      ui_macros:")
        for k, v in macros.items():
            if v is None:
                lines.append(f"        {k}:")
            else:
                lines.append(
                    f"        {k}: {yaml.safe_dump(v, default_style=chr(34)).strip()}"
                )
    else:
        lines.append("      ui_macros: {}")
    return lines


def set_pvi_blocks(text: str, blocks: dict[str, list[str]]) -> str:
    """Support yaml text with each named model's pvi: block set (text-level,
    so comments and layout are kept)."""
    lines = text.splitlines()
    out: list[str] = []
    model_starts = [
        i for i, line in enumerate(lines) if re.match(r"^  - name:\s*\S", line)
    ]
    if not model_starts:
        return text
    out = lines[: model_starts[0]]
    bounds = model_starts + [len(lines)]
    for start, end in itertools.pairwise(bounds):
        chunk = lines[start:end]
        name = chunk[0].split("name:", 1)[1].strip().strip("\"'")
        if name not in blocks:  # e.g. a hand-edited device: leave its pvi block
            out += chunk
            continue
        # drop any existing pvi block
        kept, skip = [], False
        for line in chunk:
            if re.match(r"^    pvi:\s*$", line):
                skip = True
                continue
            if skip and (line.startswith("      ") or not line.strip()):
                if not line.strip():
                    skip = False
                    kept.append(line)
                continue
            skip = False
            kept.append(line)
        # trailing blank lines stay after the block
        tail = []
        while kept and not kept[-1].strip():
            tail.insert(0, kept.pop())
        out += kept + blocks[name] + tail
    return "\n".join(out) + ("\n" if text.endswith("\n") else "")


@dataclass
class Result:
    pattern: str
    model: str
    status: str  # written, unchanged, skipped-hand-edited, no-records, ...
    counts: dict[str, int] = field(default_factory=dict)
    note: str = ""


def process_pattern(
    pattern: Path, check: bool, report: list, scratch: Path
) -> list[Result]:
    results: list[Result] = []
    supports = sorted(pattern.glob(f"*{SUPPORT_SUFFIX}"))
    annotations = history_annotations(pattern)
    overrides = load_overrides(pattern)
    for support in supports:
        blocks: dict[str, list[str]] = {}
        for m in models_of(support):
            mname = m["name"]
            dbs = m.get("databases") or []
            if not dbs:
                results.append(Result(pattern.name, mname, "no-databases"))
                continue
            parser = Parser(pattern, annotations)
            args: dict = {}
            commands: list = []
            for db in dbs:
                parser.parse(db["file"])
                args.update(db.get("args") or {})
                commands += annotations.get((db["file"], "commands"), [])
            records = parser.records
            if not records:
                results.append(Result(pattern.name, mname, "no-records"))
                continue
            annotated = any(r.gui for r in records)
            model = Model(records, overrides.get(mname, {}))
            placed = []
            for r in records:
                place, reason = model.classify(r, annotated)
                placed.append(Placed(r, place, reason))
            pair_readbacks(placed)
            macros, subs, unresolved = ui_macros(
                records, m.get("parameters") or {}, args
            )
            builder = Builder(model, subs)
            device = build_device(mname, placed, commands, builder)
            counts = {k: sum(p.place == k for p in placed) for k in PLACES}
            counts["records"] = len(records)
            counts["signals"] = sum(
                len(g.children) for g in device.children if isinstance(g, Group)
            )
            counts["rw_pairs"] = sum(1 for p in placed if p.readback)
            note = f"unresolved macros {unresolved}" if unresolved else ""
            for p in placed:
                report.append(
                    (
                        pattern.name,
                        mname,
                        p.record.name,
                        p.record.rtype,
                        p.place,
                        p.reason,
                        p.readback.name if p.readback else "",
                        "paired" if p.paired else "",
                    )
                )
            device_file = f"{mname}{DEVICE_SUFFIX}"
            path = pattern / device_file
            why = hand_edited(path)
            if why:
                results.append(
                    Result(
                        pattern.name,
                        mname,
                        f"skipped-hand-edited ({why})",
                        counts,
                        note,
                    )
                )
                continue
            text = render(device, scratch)
            status = (
                "unchanged" if path.exists() and path.read_text() == text else "written"
            )
            if status == "written" and not check:
                path.write_text(text)
            blocks[mname] = pvi_block(device_file, macros)
            results.append(Result(pattern.name, mname, status, counts, note))
        old = support.read_text()
        new = set_pvi_blocks(old, blocks)
        if new != old:
            if not check:
                support.write_text(new)
            results.append(Result(pattern.name, support.name, "support-yaml-updated"))
    return results


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("patterns", nargs="*", help="pattern folders (default all)")
    parser.add_argument(
        "--check",
        action="store_true",
        help="change nothing; exit 1 if anything would change",
    )
    parser.add_argument(
        "--report", type=Path, help="write a per-record classification TSV"
    )
    args = parser.parse_args()
    patterns = (
        [ROOT / p for p in args.patterns]
        if args.patterns
        else sorted(
            d
            for d in ROOT.iterdir()
            if d.is_dir()
            and not d.name.startswith(".")
            and any(d.glob(f"*{SUPPORT_SUFFIX}"))
        )
    )
    import tempfile

    report: list = []
    changed = False
    with tempfile.TemporaryDirectory() as tmp:
        for pattern in patterns:
            for res in process_pattern(pattern, args.check, report, Path(tmp)):
                c = res.counts
                counts = (
                    f" records={c['records']} signals={c['signals']} main={c[MAIN]} "
                    f"settings={c[SETTINGS]} comms={c[COMMS]} internal={c[INTERNAL]} "
                    f"rw={c['rw_pairs']}"
                    if c
                    else ""
                )
                print(
                    f"{res.pattern}/{res.model}: {res.status}{counts} {res.note}".rstrip()
                )
                if res.status in ("written", "support-yaml-updated"):
                    changed = True
    if args.report:
        args.report.write_text(
            "pattern\tmodel\trecord\ttype\tplace\treason\treadback\tpaired\n"
            + "".join("\t".join(row) + "\n" for row in report)
        )
    return 1 if args.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
