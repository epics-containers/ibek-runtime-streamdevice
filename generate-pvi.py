def pascal(text: str) -> str:
    words = []
    for word in re.split(r"[^A-Za-z0-9]+", text):
        words += re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+", word) or [word]
    out = "".join(w[:1].upper() + w[1:].lower() for w in words if w)
    if not out or not out[0].isalpha():
        out = "N" + out
    return out


class Names:
    def __init__(self):
        self.used: set[str] = set()

    def __call__(self, text: str) -> str:
        base = pascal(text)
        name, n = base, 1
        while name in self.used:
            n += 1
            name = f"{base}{n}"
        self.used.add(name)
        return name


def record_suffix(name: str) -> str:
    """The record name less its leading macros, for naming signals."""
    stripped = MACRO.sub(" ", name).strip(" :_-.")
    return stripped or name


def read_widget(r: Record):
    if r.rtype in ("bi", "busy"):
        return LED()
    if r.rtype in ("stringin", "lsi"):
        return TextRead(format=TextFormat.string)
    if r.rtype in ("waveform", "aai", "subArray"):
        ftvl = r.fields.get("FTVL", "")
        nelm = r.fields.get("NELM", "1")
        if ftvl in ("CHAR", "UCHAR", "STRING") or not nelm.isdigit():
            return TextRead(format=TextFormat.string)
        if int(nelm) > 1:
            return ArrayTrace(axis="x")
    return TextRead()


def write_widget(r: Record):
    if r.rtype in ("bo", "busy"):
        return ToggleButton()
    if r.rtype == "mbbo":
        return ComboBox()
    if r.rtype in ("stringout", "lso"):
        return TextWrite(format=TextFormat.string)
    return TextWrite()


class Builder:
    def __init__(self, model: Model, substitutions: dict[str, str]):
        self.model = model
        self.subs = substitutions
        self.names = Names()

    def pv(self, name: str) -> str:
        """PV for the screen: defaults resolved, ui macros left as $(X)."""

        def sub(m: re.Match) -> str:
            if m[1] in self.subs:
                return self.subs[m[1]]
            return f"$({m[1]})"

        return MACRO.sub(sub, name)

    def label(self, r: Record) -> str:
        if r.gui:
            return r.gui[1]
        return r.desc or r.controldesk or record_suffix(r.name)

    def is_action(self, p: Placed) -> bool:
        r = p.record
        if r.gui and r.gui[0] == "command":
            return True
        if p.readback or r.rtype not in ("bo", "longout"):
            return False
        if (
            r.rtype == "bo"
            and r.device
            and not r.autosave_val
            and ACTION_TOKENS & set(name_tokens(r))
        ):
            return True
        return (
            not r.device
            and r.fields.get("SCAN", "Passive") == "Passive"
            and bool(self.model.forwarded[r.name] or self.model.writes[r.name])
            and not r.autosave_val
        )

    def signal(self, p: Placed):
        r = p.record
        name = self.names(record_suffix((p.readback or r).name))
        label = self.label(r)
        desc = r.desc if r.desc and r.desc != label else None
        if r.rtype in OUTPUT_TYPES:
            if self.is_action(p):
                return SignalX(
                    name=name,
                    label=label,
                    description=desc,
                    write_pv=self.pv(r.name),
                    value="1",
                )
            if p.readback:
                return SignalRW(
                    name=name,
                    label=label,
                    description=desc,
                    write_pv=self.pv(r.name),
                    write_widget=write_widget(r),
                    read_pv=self.pv(p.readback.name),
                    read_widget=read_widget(p.readback),
                )
            if (
                r.gui
                and r.gui[0] in ("demand", "enum", "demandString")
                or r.rtype
                in (
                    "bo",
                    "mbbo",
                    "ao",
                    "longout",
                    "stringout",
                )
            ):
                return SignalRW(
                    name=name,
                    label=label,
                    description=desc,
                    write_pv=self.pv(r.name),
                    write_widget=write_widget(r),
                    read_widget=read_widget(r)
                    if r.rtype not in ("bo", "busy")
                    else LED(),
                )
            return SignalW(
                name=name,
                label=label,
                description=desc,
                write_pv=self.pv(r.name),
                write_widget=write_widget(r),
            )
        return SignalR(
            name=name,
            label=label,
            description=desc,
            read_pv=self.pv(r.name),
            read_widget=read_widget(r),
        )

    def command(self, label: str, pv: str):
        return SignalX(
            name=self.names(label), label=label, write_pv=self.pv(pv), value="1"
        )


def build_device(
    label: str,
    placed: list[Placed],
    commands: list[tuple[str, str, str]],
    builder: Builder,
) -> Device:
    groups: dict[str, list] = {}
    order: list[str] = []

    def add(group: str, component) -> None:
        if group not in groups:
            groups[group] = []
            order.append(group)
        groups[group].append(component)

    main = label
    # main first, then gui headings in order, then settings, comms, internal
    add_main = []
    position = {p.record.name: p.record.order for p in placed}
    for p in placed:
        if p.readback:
            position[p.record.name] = min(p.record.order, p.readback.order)
    for p in sorted(placed, key=lambda p: position[p.record.name]):
        if p.paired:
            continue
        sig = builder.signal(p)
        if p.place == MAIN:
            heading = p.record.gui[2] if p.record.gui and p.record.gui[2] else main
            add_main.append((heading, sig))
        else:
            add(
                {SETTINGS: "Settings", COMMS: "Comms", INTERNAL: "Internal"}[p.place],
                sig,
            )
    for lbl, pv, heading in commands:
        add_main.append((heading or main, builder.command(lbl, pv)))
    main_groups: dict[str, list] = {}
    for heading, sig in add_main:
        main_groups.setdefault(heading, []).append(sig)
    group_names = Names()
    children = []
    for heading, sigs in main_groups.items():
        children.append(
            Group(
                name=group_names(heading), label=heading, layout=Grid(), children=sigs
            )
        )
    for g in ("Settings", "Comms", "Internal"):
        if g in groups:
            layout = SubScreen() if g == "Internal" else Grid()
            children.append(
                Group(name=group_names(g), label=g, layout=layout, children=groups[g])
            )
    return Device(label=label, children=children)


