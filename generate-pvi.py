def link_target(value: str, names: set[str]) -> str | None:
    """The record a link field points at, if it is one of names."""
    value = value.strip()
    if not value or value.startswith(("@", "#")):
        return None
    target = value.split()[0].split(".")[0]
    return target if target in names else None


def name_tokens(record: Record) -> list[str]:
    """Upper-case tokens of the record name after its leading macros."""
    suffix = MACRO.sub(" ", record.name)
    parts = []
    for word in re.split(r"[^A-Za-z0-9]+", suffix):
        parts += re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+", word) or [word]
    return [p.upper() for p in parts if p]


@dataclass
class Placed:
    record: Record
    place: str
    reason: str
    readback: Record | None = None  # for outputs: the paired input
    paired: bool = False  # an input shown as another record's readback


class Model:
    def __init__(self, records: list[Record], overrides: dict[str, list[str]]):
        self.records = records
        self.by_name = {r.name: r for r in records}
        names = set(self.by_name)
        self.readers: dict[str, set[str]] = {n: set() for n in names}
        self.writes: dict[str, set[str]] = {n: set() for n in names}
        self.sdis: set[str] = set()
        self.forwarded: dict[str, set[str]] = {n: set() for n in names}
        for r in records:
            for fname, value in r.fields.items():
                t = link_target(value, names)
                if t is None or t == r.name:
                    continue
                if fname == "SDIS":
                    self.sdis.add(t)
                elif READ_LINK.match(fname):
                    self.readers[t].add(r.name)
                elif WRITE_LINK.match(fname) and r.rtype not in ("fanout", "seq"):
                    self.writes[r.name].add(t)
                elif FORWARD_LINK.match(fname) or (
                    WRITE_LINK.match(fname) and r.rtype in ("fanout", "seq")
                ):
                    self.forwarded[r.name].add(t)
        self.overrides = [
            (place, re.compile(rx))
            for place in PLACES
            for rx in overrides.get(place, [])
        ]

    def plumbing(self, r: Record) -> bool:
        return r.rtype in PLUMBING_TYPES

    def flows_to(self, name: str) -> set[str]:
        """Records whose value is computed from name's value."""
        out = set(self.readers[name]) | set(self.writes[name])
        return out

    def feeds_presentation(self, r: Record) -> bool:
        """r's value reaches a non-plumbing record, possibly via plumbing.

        A direct copy into a record of the same type (one reply fanned out to
        per-channel records) does not count: r is then a value in its own right.
        """
        seen = {r.name}
        todo = [(n, True) for n in self.flows_to(r.name)]
        while todo:
            n, direct = todo.pop()
            if n in seen:
                continue
            seen.add(n)
            t = self.by_name[n]
            if not self.plumbing(t):
                if direct and t.rtype == r.rtype:
                    continue
                return True
            todo += [(m, False) for m in self.flows_to(n)]
        return False

    def tagged(self, r: Record) -> bool:
        return bool(r.controldesk or r.archived)

    def classify(self, r: Record, annotated: bool) -> tuple[str, str]:
        for place, rx in self.overrides:
            if rx.fullmatch(r.raw_name) or rx.fullmatch(r.name):
                return place, "override"
        if r.gui:
            return MAIN, "gui annotation"
        tokens = name_tokens(r)
        if r.rtype == "asyn" or r.dtyp == "asynRecordDevice":
            return COMMS, "asyn record"
        if r.name in self.sdis or COMMS_TOKENS & set(tokens):
            return COMMS, "comms disable/counter"
        if self.plumbing(r):
            if (
                r.rtype in ("calc", "scalcout", "acalcout")
                and r.desc
                and not self.readers[r.name]
                and not self.writes[r.name]
            ):
                pass  # a final computed value
            elif self.tagged(r) and r.rtype in ("calc", "scalcout"):
                pass
            else:
                return INTERNAL, f"plumbing type {r.rtype}"
        if not self.tagged(r):
            if (
                r.rtype not in OUTPUT_TYPES
                and not (r.rtype in ("ai", "bi", "mbbi") and r.desc)
                and r.rtype != "motor"
                and self.feeds_presentation(r)
            ):
                return INTERNAL, "feeds another record"
            if (
                r.device
                and r.rtype in OUTPUT_TYPES
                and r.fields.get("SCAN", "Passive") not in ("Passive", "I/O Intr")
            ):
                return INTERNAL, "periodic poller"
            if (
                r.device
                and r.rtype in ("stringin", "waveform")
                and self.forwarded[r.name]
            ):
                return INTERNAL, "raw reply"
            if (
                (INTERNAL_TOKENS & set(tokens))
                or any(t.startswith(INTERNAL_PREFIXES) for t in tokens)
                or re.search(r"(^|[:.-])_", MACRO.sub("M", r.name))
            ):
                return INTERNAL, "internal name"
            if (
                r.device
                and r.rtype in OUTPUT_TYPES
                and any(
                    r.name in self.forwarded[o.name] and o.rtype in OUTPUT_TYPES
                    for o in self.records
                )
            ):
                return INTERNAL, "device write forwarded from a setpoint"
        if r.rtype in OUTPUT_TYPES and r.autosave_val:
            return SETTINGS, "autosaved"
        if annotated and not self.tagged(r):
            return INTERNAL, "not on the DLS screen"
        if (
            not r.device
            and not r.desc
            and r.rtype not in OUTPUT_TYPES | INPUT_TYPES
            and not self.tagged(r)
        ):
            return INTERNAL, "soft record, no DESC"
        return MAIN, "default"


WRITE_MARKERS = {
    "SP",
    "SET",
    "S",
    "DMD",
    "DEMAND",
    "W",
    "WR",
    "WRITE",
    "OUT",
    "CMD",
    "SETPOINT",
}
READ_MARKERS = {
    "RBV",
    "RB",
    "R",
    "RD",
    "READ",
    "IN",
    "GET",
    "RDBK",
    "READBACK",
    "MON",
    "ACT",
    "ACTUAL",
    "STATE",
    "STAT",
}
GLUED_PREFIXES = ("SET", "GET", "READ", "RD", "WR")
GLUED_SUFFIXES = ("RBV", "SP", "RB")


def pair_key(name: str, markers: set[str]) -> str:
    """Name with read/write markers removed, for readback pairing."""
    tokens = [t for t in re.split(r"[^A-Za-z0-9$()]+", name.upper()) if t]
    tokens = [t for t in tokens if t not in markers]
    if tokens:
        last = tokens[-1]
        for p in GLUED_PREFIXES:
            if last.startswith(p) and len(last) > len(p) + 1:
                tokens[-1] = last[len(p) :]
                break
        last = tokens[-1]
        for s in GLUED_SUFFIXES:
            if last.endswith(s) and len(last) > len(s) + 1:
                tokens[-1] = last[: -len(s)]
                break
    return ":".join(tokens)


def pair_readbacks(placed: list[Placed]) -> None:
    """Pair each output record with an input record that reads it back."""
    inputs = [
        p
        for p in placed
        if p.record.rtype in INPUT_TYPES or p.record.rtype in ("calc", "scalcout")
    ]
    keys: dict[str, list[Placed]] = {}
    for p in inputs:
        keys.setdefault(
            pair_key(p.record.name, WRITE_MARKERS | READ_MARKERS), []
        ).append(p)
    for p in placed:
        if p.record.rtype not in OUTPUT_TYPES:
            continue
        key = pair_key(p.record.name, WRITE_MARKERS | READ_MARKERS)
        candidates = [
            c for c in keys.get(key, []) if not c.paired and c.place != INTERNAL
        ]
        if not candidates:
            continue
        best = min(candidates, key=lambda c: (len(c.record.name), c.record.name))
        p.readback = best.record
        best.paired = True
        best.place = p.place


