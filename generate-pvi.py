@dataclass
class Record:
    rtype: str
    name: str  # macros expanded through substitute/include, template macros kept
    raw_name: str  # as written in its file
    file: str
    order: int
    fields: dict[str, str] = field(default_factory=dict)
    gui: tuple[str, str, str] | None = None  # (kind, label, group heading)
    controldesk: str | None = None
    archived: bool = False
    autosave_val: bool = False

    @property
    def dtyp(self) -> str:
        return self.fields.get("DTYP", "")

    @property
    def device(self) -> bool:
        return self.dtyp not in SOFT_DTYPS and not self.dtyp.startswith("$(")

    @property
    def desc(self) -> str:
        return self.fields.get("DESC", "").strip()


def expand(text: str, macros: dict[str, str]) -> str:
    """Expand the substitute-defined macros in text, leaving all others."""
    for _ in range(10):
        new = MACRO.sub(lambda m: macros[m[1]] if m[1] in macros else m[0], text)
        if new == text:
            break
        text = new
    return text


def unquote(token: str) -> str:
    return token[1:-1] if token.startswith('"') else token


class Parser:
    def __init__(self, folder: Path, annotations: dict[str, dict]):
        self.folder = folder
        self.annotations = annotations
        self.records: list[Record] = []

    def parse(self, filename: str, macros: dict[str, str] | None = None) -> None:
        macros = dict(macros or {})
        text = (self.folder / filename).read_text(errors="replace")
        gui = self.annotations.get(filename, {})
        tokens = TOKEN.findall(text)
        pending: list[str] = []  # comments since the last record
        current: Record | None = None
        depth = 0
        i = 0
        while i < len(tokens):
            tok = tokens[i]
            if tok.startswith("#"):
                if current is not None and depth > 0:
                    self._comment(current, tok)
                else:
                    pending.append(tok)
                i += 1
                continue
            if depth == 0 and tok == "include":
                self.parse(unquote(tokens[i + 1]), macros)
                i += 2
                continue
            if depth == 0 and tok == "substitute":
                for pair in unquote(tokens[i + 1]).split(","):
                    if "=" in pair:
                        k, v = pair.split("=", 1)
                        macros[k.strip()] = expand(v.strip(), macros)
                i += 2
                continue
            if depth == 0 and tok in ("record", "grecord") and tokens[i + 1] == "(":
                rtype, raw = tokens[i + 2], unquote(tokens[i + 4])
                current = Record(
                    rtype=rtype,
                    name=expand(raw, macros),
                    raw_name=raw,
                    file=filename,
                    order=len(self.records),
                )
                for c in pending:
                    self._comment(current, c)
                pending = []
                ann = gui.get(raw) or self.annotations.get("*", {}).get(raw)
                if ann:
                    kind, label, heading = ann
                    current.gui = (kind, expand(label, macros), expand(heading, macros))
                self.records.append(current)
                i += 6
                continue
            if tok == "{":
                depth += 1
            elif tok == "}":
                depth -= 1
                if depth == 0:
                    current = None
                    pending = []
            elif (
                depth == 1
                and current is not None
                and tok == "field"
                and tokens[i + 1] == "("
            ):
                name, value = tokens[i + 2], tokens[i + 4]
                if value == ")":  # field(X, ) - empty value
                    current.fields[name.strip()] = ""
                    i += 5
                    continue
                current.fields[name.strip()] = expand(unquote(value), macros)
                i += 6
                continue
            i += 1

    @staticmethod
    def _comment(record: Record, comment: str) -> None:
        if m := CONTROLDESK.match(comment):
            record.controldesk = m[1]
        elif ARCHIVER.match(comment):
            record.archived = True
        elif (m := AUTOSAVE.match(comment)) and (
            m[1] in ("1", "2") and (not m[2] or "VAL" in m[2].split())
        ):
            record.autosave_val = True


def history_annotations(pattern: Path) -> dict[str, dict]:
    """{file: {raw record name: (kind, label, heading)}} from ANNOTATION_REF.

    Under the key "*", the same for all the pattern's files merged.

    Also returns, under the key (file, "commands"), the .PROC command
    annotations as a list of (label, raw pv, heading).
    """
    result: dict = {}
    check = subprocess.run(
        [
            "git",
            "-C",
            str(ROOT),
            "rev-parse",
            "--verify",
            f"{ANNOTATION_REF}^{{commit}}",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if check.returncode:
        raise SystemExit(
            f"Cannot resolve ANNOTATION_REF {ANNOTATION_REF} in {ROOT}: "
            f"{check.stderr.strip()}\n"
            "The '# % gui' annotations are read from git history, so this needs a "
            "full clone (git fetch --unshallow; in CI use actions/checkout with "
            "fetch-depth: 0), not a shallow clone or git archive."
        )
    for f in sorted(pattern.glob("*.template")) + sorted(pattern.glob("*.db")):
        rel = f"{pattern.name}/{f.name}"
        try:
            old = subprocess.run(
                ["git", "-C", str(ROOT), "show", f"{ANNOTATION_REF}:{rel}"],
                capture_output=True,
                text=True,
                check=True,
            ).stdout
        except subprocess.CalledProcessError:
            continue  # the file did not exist at ANNOTATION_REF
        heading = ""
        found: dict[str, tuple[str, str, str]] = {}
        commands: list[tuple[str, str, str]] = []
        for line in old.splitlines():
            m = GUI.match(line)
            if not m:
                continue
            kind, label, pv = m[1], m[2].strip(), (m[3] or "").strip()
            if kind == "groupHeading":
                heading = label
            elif kind == "groupExit":
                heading = ""
            elif pv:
                pv = pv.split(",")[0].strip()
                base, _, fld = pv.partition(".")
                if fld:
                    commands.append((label, pv, heading))
                else:
                    found.setdefault(base, (kind, label, heading))
        if found or commands:
            result[f.name] = found
            result[(f.name, "commands")] = commands
            # a DLS gui-only template may annotate records of another template
            for pv, ann in found.items():
                result.setdefault("*", {}).setdefault(pv, ann)
    return result


